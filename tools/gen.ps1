# Generates src/Generated/InputMap.cs from sheets/input_map.json and sheets/controls.json (the sheets are the source of truth).
$root = Split-Path $PSScriptRoot -Parent
function Rows($n) { (Get-Content (Join-Path $root "sheets\$n.json") -Raw | ConvertFrom-Json).rows }
function Q($s) { '"' + ([string]$s).Replace('\', '\\').Replace('"', '\"') + '"' }
$o = New-Object System.Collections.Generic.List[string]
$o.Add("// <auto-generated> from sheets/input_map.json and sheets/controls.json by tools/gen.ps1. Do not edit.")
$o.Add("namespace SeVr.Generated {")
$o.Add("  internal sealed class InputRow { public string Id, XrAction, Type, Hand, Path, FramePath, Target, Mode;")
$o.Add("    public InputRow(string id,string xr,string type,string hand,string path,string frame,string target,string mode){Id=id;XrAction=xr;Type=type;Hand=hand;Path=path;FramePath=frame;Target=target;Mode=mode;} }")
$o.Add("  internal static class InputMap { public static readonly InputRow[] Rows = {")
foreach ($r in Rows "input_map") { $o.Add("    new InputRow(" + ((@($r.id, $r.xrAction, $r.type, $r.hand, $r.path, $r.framePath, $r.target, $r.mode) | ForEach-Object { Q $_ }) -join ",") + "),") }
$o.Add("  }; }")
$o.Add("  internal sealed class ControlRow { public string Id, Source, GameControl, Mode, Context;")
$o.Add("    public ControlRow(string id,string source,string gc,string mode,string ctx){Id=id;Source=source;GameControl=gc;Mode=mode;Context=ctx;} }")
$o.Add("  internal static class ControlMap { public static readonly ControlRow[] Rows = {")
foreach ($r in Rows "controls") { $o.Add("    new ControlRow(" + ((@($r.id, $r.source, $r.gameControl, $r.mode, $r.context) | ForEach-Object { Q $_ }) -join ",") + "),") }
$o.Add("  }; }")
$o.Add("}")
$dir = Join-Path $root "src\Generated"; New-Item -ItemType Directory -Force $dir | Out-Null
[IO.File]::WriteAllText((Join-Path $dir "InputMap.cs"), (($o -join "`n") + "`n"), (New-Object Text.UTF8Encoding $false))
Write-Host "generated $((Rows 'input_map').Count) input rows, $((Rows 'controls').Count) control rows"
